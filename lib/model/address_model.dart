class AddressModel {
  final String name;
  final String email;
  final String phone;
  final String address;
  final String zipCode;
  final String city;
  final String country;

  AddressModel({
    required this.name,
    required this.email,
    required this.phone,
    required this.address,
    required this.zipCode,
    required this.city,
    required this.country,
  });
}
